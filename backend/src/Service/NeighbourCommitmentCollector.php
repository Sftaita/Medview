<?php

declare(strict_types=1);

namespace App\Service;

use App\Entity\Duty;
use App\Entity\PlanningPeriod;
use App\Entity\PlanningPeriodStatus;
use App\Entity\RestPolicyOptions;
use App\Repository\DutyRepository;

/**
 * The duties the people of a generation already hold elsewhere and that its
 * solve must respect (docs/decisions.md D161, docs/planning-cycles.md §5.4,
 * lot L3) — read once when the snapshot is taken (frozen as
 * PlanningSnapshotExternalCommitment), and read again, the same way, under
 * the calendar lock right before the result is written
 * (PlanningGenerationService): any difference means the result was computed
 * against a calendar that no longer exists, and it is discarded.
 *
 * Two sources, never one more:
 *
 * - the same period (cycle): the current assignments of the lines solved
 *   BEFORE this one (PlanningLineOrder) — unchanged since D161: a line
 *   solved later is about to be regenerated in the same launch and will see
 *   this one's result — and, since lot L4b (docs/decisions.md D195), of
 *   every line of the period whose period is locked (validated, published,
 *   archived), WHEREVER it stands in that order: it is never regenerated,
 *   its calendar is final;
 * - every OTHER period of the planning: the current calendar of every active
 *   line, the same line included, published or not — none of them is
 *   regenerated by this launch. Only the duties that can actually constrain
 *   this period are kept: those that overlap the span of its duties, or end
 *   or start closer to it than the strictest rest threshold that applies
 *   between the two generations (this generation's LEGAL/TEAM_MIN_REST and
 *   the owner's, PersonCommitmentChecker). No fixed margin: a farther duty
 *   cannot violate anything, a closer one is always kept.
 *
 * By person (User), like D161: only the people of the snapshot.
 *
 * $planned (docs/decisions.md D191): during a launch, nothing is written
 * before the end — the lines solved earlier are read from what they are
 * about to hold, never from their calendar that is about to be replaced.
 */
final class NeighbourCommitmentCollector
{
    private const LOCKED_STATUSES = [PlanningPeriodStatus::VALIDATED, PlanningPeriodStatus::PUBLISHED, PlanningPeriodStatus::ARCHIVED];

    public function __construct(
        private readonly PersonCommitmentReader $commitmentReader,
        private readonly PlanningLineOrder $lineOrder,
        private readonly DutyRepository $dutyRepository,
        private readonly RestGapCalculator $restGapCalculator,
    ) {
    }

    /**
     * @param array<string, true> $userStableIds the people of the snapshot
     *
     * @return list<PersonCommitment> chronological
     */
    public function collect(PlanningPeriod $period, RestPolicyOptions $own, array $userStableIds, ?PlannedCalendar $planned = null): array
    {
        $line = $period->getLine();
        $cycle = $period->getCycle();
        if (null === $line || null === $cycle) {
            return [];
        }

        $sameCycle = [];
        $preceding = true;
        foreach ($this->lineOrder->activeInCycle($cycle) as $other) {
            if ($other === $line) {
                $preceding = false;
                continue;
            }
            $otherPeriod = $other->periodIn($cycle);
            // D161: the lines solved before this one; D195: a locked line, before or after it.
            if (null !== $otherPeriod && ($preceding || \in_array($otherPeriod->getStatus(), self::LOCKED_STATUSES, true))) {
                $sameCycle[] = $otherPeriod;
            }
        }

        $otherCycles = array_values(array_filter(
            $this->commitmentReader->periodsOfActiveLines($cycle->getPlanning()),
            static fn (PlanningPeriod $other): bool => null !== $other->getCycle() && $other->getCycle() !== $cycle,
        ));

        $commitments = [];
        foreach ($this->commitmentReader->byUserStableIdInPeriods($sameCycle, $planned) as $userStableId => $held) {
            if (isset($userStableIds[$userStableId])) {
                array_push($commitments, ...$held);
            }
        }

        $span = [] !== $otherCycles ? $this->span($this->dutyRepository->findByPlanningPeriod($period)) : null;
        if (null !== $span) {
            foreach ($this->commitmentReader->byUserStableIdInPeriods($otherCycles, $planned) as $userStableId => $held) {
                if (!isset($userStableIds[$userStableId])) {
                    continue;
                }
                foreach ($held as $commitment) {
                    if ($this->canConstrain($commitment, $span, $own)) {
                        $commitments[] = $commitment;
                    }
                }
            }
        }

        usort($commitments, static fn (PersonCommitment $a, PersonCommitment $b): int => [$a->duty->getStartsAt(), (string) $a->duty->getStableId()] <=> [$b->duty->getStartsAt(), (string) $b->duty->getStableId()]);

        return $commitments;
    }

    /**
     * @param list<Duty> $duties
     *
     * @return array{0: \DateTimeImmutable, 1: \DateTimeImmutable}|null from the first duty's start to the last one's end
     */
    private function span(array $duties): ?array
    {
        if ([] === $duties) {
            return null;
        }

        $startsAt = min(array_map(static fn (Duty $duty): \DateTimeImmutable => $duty->getStartsAt(), $duties));
        $endsAt = max(array_map(static fn (Duty $duty): \DateTimeImmutable => $duty->getEndsAt(), $duties));

        return [$startsAt, $endsAt];
    }

    /**
     * Whether $commitment can make any duty of the span infeasible: an
     * overlap (CONFLICT, always HARD), or a gap shorter than the strictest
     * rest threshold of the two generations. The gap to the span is never
     * larger than the gap to any duty in it, so nothing that matters is left
     * out.
     *
     * @param array{0: \DateTimeImmutable, 1: \DateTimeImmutable} $span
     */
    private function canConstrain(PersonCommitment $commitment, array $span, RestPolicyOptions $own): bool
    {
        [$startsAt, $endsAt] = $span;
        if ($commitment->duty->getStartsAt() < $endsAt && $startsAt < $commitment->duty->getEndsAt()) {
            return true;
        }

        $owner = $commitment->generation->getRestPolicy();
        $thresholds = array_filter([
            $own->legalMinRestEnabled ? $own->legalMinRestHours : null,
            $own->teamMinRestEnabled ? $own->teamMinRestHours : null,
            $owner->legalMinRestEnabled ? $owner->legalMinRestHours : null,
            $owner->teamMinRestEnabled ? $owner->teamMinRestHours : null,
        ], static fn (?int $hours): bool => null !== $hours);
        if ([] === $thresholds) {
            return false;
        }

        $gap = $this->restGapCalculator->gapHoursBetween($startsAt, $endsAt, $commitment->duty->getStartsAt(), $commitment->duty->getEndsAt());

        return $gap < max($thresholds);
    }
}
