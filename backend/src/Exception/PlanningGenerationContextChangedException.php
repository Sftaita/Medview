<?php

declare(strict_types=1);

namespace App\Exception;

/**
 * The result of a solve is not written (docs/planning-cycles.md §5.4, lot
 * L3, docs/decisions.md D189/D191), checked under the calendar lock right
 * before writing — nothing of it is written, the generation is FAILED with
 * the reason:
 *
 * - `neighbour_calendar_changed`: what the people of the generation hold
 *   elsewhere (earlier lines of the period, other periods of the planning)
 *   is no longer what the snapshot froze — a reassignment, a completion or
 *   another generation happened during the solve;
 * - `period_locked`: the period was validated, published or archived during
 *   the solve — a published period is never regenerated (I8);
 * - `launch_inconsistent`: written with the calendars that stay as they are
 *   (a line of the launch that failed keeps its previous calendar), it would
 *   break an overlap, a rest or a self-coverage rule — `conflicts` lists them;
 * - `source_not_written`: a conditional line whose source line's result of
 *   the same launch is not written — its demand was decided from it;
 * - `source_calendar_changed` (docs/decisions.md D195): a conditional line
 *   whose source is kept (locked, not generated by this launch) — a holder
 *   of a source duty changed while the solve ran, so its demand was decided
 *   from a calendar that no longer exists.
 */
final class PlanningGenerationContextChangedException extends \RuntimeException
{
    public const NEIGHBOUR_CALENDAR_CHANGED = 'neighbour_calendar_changed';
    public const PERIOD_LOCKED = 'period_locked';
    public const LAUNCH_INCONSISTENT = 'launch_inconsistent';
    public const SOURCE_NOT_WRITTEN = 'source_not_written';
    public const SOURCE_CALENDAR_CHANGED = 'source_calendar_changed';

    /**
     * @param list<array<string, mixed>> $conflicts
     */
    public function __construct(public readonly string $reason, string $message, public readonly array $conflicts = [])
    {
        parent::__construct($message);
    }
}
