        }

        /** @var array<int, array<int, array<int, ?int>>> $byPublication publication → period → duty → user (null: uncovered) */
        $byPublication = [];
        foreach ($entries as $entry) {
            $byPublication[(int) $entry['publication_id']][(int) $entry['planning_period_id']][(int) $entry['duty_id']] = null !== $entry['user_id'] ? (int) $entry['user_id'] : null;
        }

        $rows = [];
        /** @var array<int, array<int, array<int, ?int>>> $lastByPlanning planning → period → its last published duties */
        $lastByPlanning = [];
        foreach ($publications as $publication) {
            $planningId = (int) $publication['planning_id'];
            foreach ($byPublication[(int) $publication['id']] ?? [] as $periodId => $duties) {
                $previous = $lastByPlanning[$planningId][$periodId] ?? null;
                if (null === $previous) {
                    $kind = 'FIRST_FOR_LINE';
                    $changed = 0;
                } else {
                    $changed = 0;
                    foreach (array_keys($duties + $previous) as $dutyId) {
                        $before = \array_key_exists($dutyId, $previous) ? $previous[$dutyId] : false;
                        $after = \array_key_exists($dutyId, $duties) ? $duties[$dutyId] : false;
                        if ($before !== $after) {
                            ++$changed;
                        }
                    }
                    $kind = $changed > 0 ? 'UPDATED' : null;
                }
                $lastByPlanning[$planningId][$periodId] = $duties;
                if (null === $kind) {
                    continue; // never an artificial UPDATED
                }
