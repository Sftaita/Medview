                    'publication' => (int) $publication['id'],
                    'cycle' => (int) $publication['planning_cycle_id'],
                    'period' => $periodId,
                    'lineStableId' => $lines[$periodId][0] ?? null,
                    'lineName' => $lines[$periodId][1] ?? null,
                    'kind' => $kind,
                    'dutyCount' => \count($duties),
                    'changed' => $changed,
                ];
            }
        }

        return $rows;
    }
